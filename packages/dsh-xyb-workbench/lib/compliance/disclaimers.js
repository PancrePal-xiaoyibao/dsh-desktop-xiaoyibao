/**
 * 医学安全免责声明基础设施。 SPEC §5 M7 / 治理文档 §7 六条红线。
 *
 * 设计意图：**基础设施先行**。
 * 本项目有 6 个业务模块，若各自写声明必然不一致。因此所有声明集中在此处，
 * 各模块只引用键；`docs/MEDICAL-DISCLAIMER.md` 与本文件由测试断言双向一致。
 *
 * 对应红线：
 * M-1 不做诊断 → numeric / molecular
 * M-2 不做处方 → prescribing（禁止清单，见 §FORBIDDEN）
 * M-3 不解读量表 → scale
 * M-4 不替医生判定 → matching
 * M-5 危机必须兜底 → crisis
 * M-6 一切可溯源 → （机制约束，非文案）
 */
export const DISCLAIMERS = Object.freeze({
  /** 数值解释场景（指标、卡片、营养） */
  numeric:
    '以上为数值描述与常见原因，不构成诊断。具体含义请以医生解释为准。',

  /** 分子/名词科普场景（基因、IHC） */
  molecular:
    '以上为通行教科书级描述，用于帮助你理解报告中的名词。不构成诊断或治疗建议，具体含义请以医生解释为准。',

  /** 量表场景（心理自评） */
  scale:
    '分数按各量表官方分界呈现，工作台不做解读。',

  /** 危机场景（心理支持每页常驻） */
  crisis:
    '工作台不能提供危机干预，以上为公共服务信息。',

  /** 临床匹配场景 */
  matching:
    '匹配结论不构成入组资格判定，需医生评估的项由研究医生判定。',

  /** 营养目标场景 */
  nutrition:
    '以上为按体重与常见系数计算的目标区间，不构成营养处方。具体摄入方案请以医生或临床营养师的意见为准。',

  /** 全程管理场景（中性事实） */
  care:
    '以上为记录与事实呈现，不构成医疗建议。如需判断请联系医生。',

  /** 数据主权场景 */
  dataSovereignty:
    '数据默认保存在本机。仅在你自己开启云端解析时，所选文件会上传解析；档案、记录、笔记与密钥不上传。',
})

/**
 * 禁止出现在任何界面文案中的措辞类别。
 * 由 `scripts/check-copy-compliance.mjs` 使用。
 *
 * 注意：这里的词表用于**审计**，因此用类别 + 正则，而不是逐字列出药名。
 */
export const FORBIDDEN = Object.freeze({
  /** 药物推荐（药名 + 推荐动词的组合，由脚本按正则匹配） */
  prescribing: [
    '建议服用',
    '推荐使用',
    '可以考虑使用',
    '建议加用',
    '建议停用',
    '建议换用',
    '剂量为',
    '每日服用',
    'mg/kg',
  ],
  /** 判断性表述（越界为诊断） */
  judgment: ['说明你有', '表明你', '意味着你', '你属于', '确诊为', '提示患有'],
  /** 建议性表述（全程管理尤其禁止） */
  advising: ['建议尽快', '建议及时', '务必要', '应该去', '必须去', '最好去', '需要安排'],
  /** 因果推断（全程管理关联场景禁止） */
  causal: ['导致', '引起', '造成', '引发', '因为…所以', '从而'],
})

/** 取得某个键的声明文本；未知键返回 null（调用方应视为配置错误） */
export function disclaimer(key) {
  return Object.prototype.hasOwnProperty.call(DISCLAIMERS, key) ? DISCLAIMERS[key] : null
}

/** 所有键（供一致性断言使用） */
export function disclaimerKeys() {
  return Object.keys(DISCLAIMERS)
}
